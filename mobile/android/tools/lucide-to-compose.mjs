// Generates app/src/main/java/com/noctgram/app/Lucide.kt from the lucide-react
// package the website already uses, so the app draws exactly the site's icons.
// Run from mobile/android after `npm ci` in the repository root:
//   node tools/lucide-to-compose.mjs
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const icons = join(here, '../../../node_modules/lucide-react/dist/esm/icons');
const out = join(here, '../app/src/main/java/com/noctgram/app/Lucide.kt');

// [lucide name, Kotlin name, also a filled variant]
const wanted = [
  ['house', 'House'], ['message-circle', 'MessageCircle'], ['user', 'User'], ['search', 'Search'],
  ['heart', 'Heart', true], ['bookmark', 'Bookmark', true], ['eye', 'Eye'], ['star', 'Star', true],
  ['send-horizontal', 'Send'], ['paperclip', 'Paperclip'], ['image', 'Image'], ['code-xml', 'Code'],
  ['chart-no-axes-column', 'Poll'], ['face-slightly-smiling', 'Smile'], ['clock', 'Clock'], ['arrow-left', 'ArrowLeft'],
  ['plus', 'Plus'], ['square-pen', 'SquarePen'], ['settings', 'Settings'], ['copy', 'Copy'],
  ['calendar', 'Calendar'], ['chevron-right', 'ChevronRight'], ['x', 'X'], ['ellipsis', 'Ellipsis'],
  ['check', 'Check'], ['check-check', 'CheckCheck'], ['camera', 'Camera'], ['sparkles', 'Sparkles'],
  ['log-out', 'LogOut'], ['link', 'Link'], ['lock', 'Lock'], ['users', 'Users'],
  ['triangle-alert', 'TriangleAlert'], ['refresh-cw', 'RefreshCw'], ['badge-check', 'BadgeCheck', true],
  ['palette', 'Palette'], ['image-plus', 'ImagePlus'], ['reply', 'Reply'], ['eye-off', 'EyeOff'],
  ['shield-check', 'ShieldCheck'], ['circle-minus', 'CircleMinus'], ['gift', 'Gift'], ['rotate-ccw-clock', 'History'],
  ['store', 'Store'], ['film', 'Film'], ['headphones', 'Headphones'], ['rotate-cw', 'RotateCw'],
  ['chevron-left', 'ChevronLeft'], ['chevron-down', 'ChevronDown'], ['hash', 'Hash'], ['external-link', 'ExternalLink'],
  ['wallet', 'Wallet'],
];

const n = (v) => Number(v);
function toPath([tag, a]) {
  switch (tag) {
    case 'path': return a.d;
    case 'circle': case 'ellipse': {
      const rx = n(a.rx ?? a.r), ry = n(a.ry ?? a.r), cx = n(a.cx), cy = n(a.cy);
      return `M${cx - rx} ${cy}a${rx} ${ry} 0 1 0 ${2 * rx} 0a${rx} ${ry} 0 1 0 ${-2 * rx} 0`;
    }
    case 'rect': {
      const x = n(a.x ?? 0), y = n(a.y ?? 0), w = n(a.width), h = n(a.height);
      const rx = Math.min(n(a.rx ?? a.ry ?? 0), w / 2), ry = Math.min(n(a.ry ?? a.rx ?? 0), h / 2);
      if (!rx) return `M${x} ${y}h${w}v${h}h${-w}z`;
      return `M${x + rx} ${y}h${w - 2 * rx}a${rx} ${ry} 0 0 1 ${rx} ${ry}v${h - 2 * ry}a${rx} ${ry} 0 0 1 ${-rx} ${ry}h${-(w - 2 * rx)}a${rx} ${ry} 0 0 1 ${-rx} ${-ry}v${-(h - 2 * ry)}a${rx} ${ry} 0 0 1 ${rx} ${-ry}z`;
    }
    case 'line': return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`;
    case 'polyline': case 'polygon': {
      const p = a.points.trim().split(/[\s,]+/);
      let d = `M${p[0]} ${p[1]}`;
      for (let i = 2; i < p.length; i += 2) d += `L${p[i]} ${p[i + 1]}`;
      return tag === 'polygon' ? d + 'z' : d;
    }
    default: throw new Error('Unsupported SVG element: ' + tag);
  }
}

let body = '';
for (const [name, kotlin, filled] of wanted) {
  const { __iconNode } = await import(pathToFileURL(join(icons, name + '.mjs')).href);
  const paths = __iconNode.map(toPath).map((d) => JSON.stringify(d)).join(', ');
  body += `    val ${kotlin} = stroked(${paths})\n`;
  if (filled) body += `    val ${kotlin}Filled = filled(${paths})\n`;
}

writeFileSync(out, `package com.noctgram.app

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.StrokeCap
import androidx.compose.ui.graphics.StrokeJoin
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.addPathNodes
import androidx.compose.ui.unit.dp

// Generated by tools/lucide-to-compose.mjs from lucide-react (ISC license, https://lucide.dev),
// the icon set of the website. Do not edit by hand: add a name there and run the script.
object Lucide {
${body}}

private fun build(paths: Array<out String>, fill: Boolean) =
    ImageVector.Builder(defaultWidth = 24.dp, defaultHeight = 24.dp, viewportWidth = 24f, viewportHeight = 24f).apply {
        for (d in paths) addPath(
            addPathNodes(d),
            fill = if (fill) SolidColor(Color.Black) else null,
            stroke = SolidColor(Color.Black),
            strokeLineWidth = 2f,
            strokeLineCap = StrokeCap.Round,
            strokeLineJoin = StrokeJoin.Round,
        )
    }.build()

private fun stroked(vararg paths: String) = build(paths, fill = false)
private fun filled(vararg paths: String) = build(paths, fill = true)
`);
console.log('Wrote ' + wanted.length + ' icons to ' + out);
